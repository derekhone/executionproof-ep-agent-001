#!/usr/bin/env bash
# EP-AGENT-001 — lockfile generation + clean-environment verification (checklist item 6).
# SETUP ONLY. Installs packages; runs no study case; contacts no ExecutionProof endpoint; reads no fixture.
#
# Method:
#   input  : $FREEZE_DIR/<fw>.freeze  = `pip freeze --all` of a clean venv in which ONLY the pinned framework
#            package was installed (pip 23.2.1, CPython 3.11.6, Linux x86_64); pip/setuptools/wheel removed.
#   pass 1 : fresh venv -> pip install --no-deps -r freeze --report  (records the exact artifact + sha256 used)
#   build  : locks/<fw>.lock  = "name==version --hash=sha256:<artifact hash>" for every package (sorted)
#   pass 2 : second fresh venv -> pip install --no-deps --require-hashes -r locks/<fw>.lock
#            -> pip check -> check_versions.py --framework <fw>
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PYTHON="${PYTHON:-python3.11}"
FREEZE_DIR="${FREEZE_DIR:?set FREEZE_DIR}"
WORK="${WORK:?set WORK (scratch dir outside the packet)}"
mkdir -p "$ROOT/locks" "$WORK"

for fw in openai_agents langgraph crewai maf; do
  echo "=== [$fw] pass 1 (resolve + record artifact hashes)"
  rm -rf "$WORK/p1_$fw" "$WORK/p2_$fw"
  "$PYTHON" -m venv "$WORK/p1_$fw"
  "$WORK/p1_$fw/bin/python" -m pip install -q --no-deps -r "$FREEZE_DIR/$fw.freeze" --report "$WORK/$fw.report.json"
  "$PYTHON" - "$WORK/$fw.report.json" "$ROOT/locks/$fw.lock" "$fw" <<'PY'
import json, sys
report, out, fw = sys.argv[1:4]
rows = []
for item in json.load(open(report))["install"]:
    meta = item["metadata"]
    h = item["download_info"].get("archive_info", {}).get("hashes", {}).get("sha256") \
        or item["download_info"]["archive_info"]["hash"].split("=", 1)[1]
    rows.append(f'{meta["name"].lower()}=={meta["version"]} --hash=sha256:{h}')
hdr = [f"# EP-AGENT-001 lockfile — framework venv: {fw}",
       "# Target: CPython 3.11.x, Linux x86_64 (manylinux wheels). pip 23.2.1.",
       "# Install: pip install --no-deps --require-hashes -r this_file",
       "# Generated by scripts/setup/generate_and_verify_locks.sh — SETUP ARTIFACT, NOT EXPERIMENTAL EVIDENCE"]
open(out, "w").write("\n".join(hdr + sorted(rows)) + "\n")
print(f"{fw}: {len(rows)} pinned packages with sha256")
PY
  echo "=== [$fw] pass 2 (clean venv, --require-hashes)"
  "$PYTHON" -m venv "$WORK/p2_$fw"
  "$WORK/p2_$fw/bin/python" -m pip install -q --no-deps --require-hashes -r "$ROOT/locks/$fw.lock"
  "$WORK/p2_$fw/bin/python" -m pip check
  "$WORK/p2_$fw/bin/python" "$ROOT/scripts/setup/check_versions.py" --framework "$fw"
done
echo "LOCK VERIFICATION COMPLETE (setup only; no study case run)."
