#!/usr/bin/env python3
"""
EP-AGENT-001 study runner — GATED. EXECUTION IS NOT AUTHORIZED IN THIS PACKET VERSION.

The runner refuses unless ALL of the following exist and verify, and even then this packet version (v0.3
FINAL PRE-FILING CANDIDATE LOCK) still refuses: enabling execution requires a separately committed,
Derek-authorized amendment.
  1. --filing-record : JSON of the FILED preregistration {platform, registration_id, url, filed_at, manifest_sha256}
  2. --gate-record   : JSON {q8_formal: "PASS", q9: "PASSED", approved_by: "Derek Hone", date}
  3. --auth-token    : Derek authorization token file (format defined by Derek; never generated by tooling)
  4. MANIFEST.sha256 verifies (sha256sum -c) and equals filing-record manifest_sha256
"""
import argparse, hashlib, json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NOT_AUTHORIZED = ("EP-AGENT-001 execution NOT AUTHORIZED: requires a filed preregistration record, Q8 formal PASS, "
                  "Q9 PASSED, a Derek Hone authorization token, and a verified manifest. This packet version refuses "
                  "unconditionally.")


def gate_failures(a) -> list:
    fails = []
    for flag, path in (("--filing-record", a.filing_record), ("--gate-record", a.gate_record), ("--auth-token", a.auth_token)):
        if not path or not Path(path).is_file():
            fails.append(f"missing {flag}")
    if a.gate_record and Path(a.gate_record).is_file():
        g = json.loads(Path(a.gate_record).read_text())
        if g.get("q8_formal") != "PASS" or g.get("q9") != "PASSED":
            fails.append("gate record lacks Q8 formal PASS / Q9 PASSED")
    ok = subprocess.run(["sha256sum", "-c", "--quiet", "MANIFEST.sha256"], cwd=ROOT, capture_output=True).returncode == 0
    if not ok:
        fails.append("MANIFEST.sha256 does not verify")
    if a.filing_record and Path(a.filing_record).is_file():
        m = hashlib.sha256((ROOT / "MANIFEST.sha256").read_bytes()).hexdigest()
        if json.loads(Path(a.filing_record).read_text()).get("manifest_sha256") != m:
            fails.append("filing record manifest_sha256 mismatch")
    return fails


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--filing-record"); ap.add_argument("--gate-record"); ap.add_argument("--auth-token")
    ap.add_argument("--framework", choices=["openai_agents", "langgraph", "crewai", "maf", "all"], default="all")
    a = ap.parse_args(argv or [])
    fails = gate_failures(a)
    msg = NOT_AUTHORIZED + (" Gate failures: " + "; ".join(fails) if fails else " (all gate inputs present; still refused in v0.3)")
    raise NotImplementedError(msg)


if __name__ == "__main__":
    try:
        main(sys.argv[1:])
    except NotImplementedError as e:
        print(f"REFUSED: {e}", file=sys.stderr); sys.exit(2)
